package tp2.ejercicio9;

public class SumaResta {
	private int suma;
	private int resta;
	
	
	public SumaResta(int suma, int resta) {
		this.suma = suma;
		this.resta = resta;
	}
	public int getSuma() {
		return suma;
	}
	public void setSuma(int suma) {
		this.suma = suma;
	}
	public int getResta() {
		return resta;
	}
	public void setResta(int resta) {
		this.resta = resta;
	}
	
	
}
